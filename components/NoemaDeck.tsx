const slides = [Thesis, Protocol, Agent500, Roadmap, Funding];

export default function NoemaDeck() {
  const [active, setActive] = useState(0);
  const viewport = useRef<HTMLDivElement>(null);
  useEffect(() => {
    document.querySelector('.deck-main-nav a[aria-current="page"]')?.scrollIntoView({ block: "nearest", inline: "nearest", behavior: "instant" });
    const readHash = () => setActive(deckChapterIndex(window.location.hash));
    readHash(); window.addEventListener("hashchange", readHash);
    window.addEventListener("popstate", readHash);
    return () => { window.removeEventListener("hashchange", readHash); window.removeEventListener("popstate", readHash); };
  }, []);
  useEffect(() => {
    viewport.current?.scrollTo({ top: 0, behavior: "instant" });
    document.querySelector('.deck-index button[aria-current="step"]')?.scrollIntoView({ block: "nearest", inline: "nearest", behavior: "instant" });
  }, [active]);
  const select = (index: number) => {
    const next = nextDeckChapter(index, 0);
    setActive(next);
    window.history.replaceState(null, "", `#${DECK_CHAPTERS[next].id}`);
  };
  const onKeyDown = (event: KeyboardEvent<HTMLDivElement>) => {
    if (event.altKey || event.ctrlKey || event.metaKey || event.shiftKey) return;
    const target = event.target as HTMLElement;
    if (target.closest("input, select, textarea, [contenteditable=true]")) return;
    let next: number | null = null;
    if (["ArrowRight", "PageDown"].includes(event.key)) next = nextDeckChapter(active, 1);
    if (["ArrowLeft", "PageUp"].includes(event.key)) next = nextDeckChapter(active, -1);
    if (event.key === "Home") next = 0;
    if (event.key === "End") next = DECK_CHAPTERS.length - 1;
    if (next !== null) { event.preventDefault(); select(next); }
  };
  const Slide = slides[active];
  return (
    <div className="deck-shell" onKeyDown={onKeyDown}>
      <aside className="deck-index">
        <div className="deck-index-title"><span>Project deck</span><span className="deck-draft">Working draft</span></div>
        <nav aria-label="Deck chapters">
          {DECK_CHAPTERS.map((chapter, index) => <button key={chapter.id} type="button" onClick={() => select(index)} aria-current={index === active ? "step" : undefined} aria-controls="deck-slide">
            <span className="deck-chapter-number">0{index + 1}</span><span><b>{chapter.title}</b><small>{chapter.label}</small></span>
          </button>)}
        </nav>
        <p className="deck-index-note">Machine culture<br />in formation.</p>
      </aside>
      <div className="deck-stage">
        <div className="deck-slide" ref={viewport} id="deck-slide" tabIndex={0} aria-label="Deck slide. Use left and right arrow keys to change chapters.">
          <div className="deck-slide-inner" key={active}><Slide /></div>
        </div>
        <footer className="deck-controls">
          <div className="deck-position" aria-live="polite" aria-atomic="true"><b>0{active + 1}</b><span>/ 05</span><span className="deck-current-title">{DECK_CHAPTERS[active].title}</span></div>
          <div className="deck-navigation"><span className="deck-key-hint">← → to navigate</span>
            <button type="button" onClick={() => select(active - 1)} disabled={active === 0} aria-label="Previous chapter">← <span>Previous</span></button>
            <button type="button" onClick={() => select(active + 1)} disabled={active === DECK_CHAPTERS.length - 1} aria-label="Next chapter"><span>Next</span> →</button>
          </div>
        </footer>
      </div>
    </div>
  );
}
